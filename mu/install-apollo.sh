#!/usr/bin/env bash
# Add apollo (Xiaomi Mi 10T / 10T Pro, SM8250) to a Mu-Silicium checkout, then build with
#   cd ~/Mu-Silicium && python3 build_uefi.py -d apollo        -> Mu-apollo.img
#
#   bash install-apollo.sh            (MU=~/Mu-Silicium, EDK=~/edk2-msm by default)
#
# What it installs:
#   Platforms/Xiaomi/apolloPkg        - derived from Silicium's aliothPkg (Poco F3, the closest SM8250 phone
#                                       with working Windows); SOC_TYPE 0 (SM8250), apollo SMBIOS, Qualcomm
#                                       charger drivers left out; firmware binaries are Silicium's alioth set
#                                       (Xiaomi's shared Kona XBL, which also carries apollo's J3S panel config)
#   Resources/Configs/apollo.toml     - same boot image settings as pipa/alioth
#   Resources/DTBs/apollo.dtb         - apollo's stock device tree (board-id 0x2a), taken from edk2-msm
#   Silicium-ACPI/Platforms/Xiaomi/apollo/
#                                     - DSDT.aml generated by make-apollo-dsdt.py from pipa's table (no thermal
#                                       zones, no PRTC), plus AcpiTables.inf listing Silicium's Kona tables
set -euo pipefail

HERE=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
MU=${MU:-$HOME/Mu-Silicium}
EDK=${EDK:-$HOME/edk2-msm}
GEN=$HERE/../uefi/apollo/make-apollo-dsdt.py
DTB=$EDK/Platform/Xiaomi/sm8250/FdtBlob_compat/apollo.dtb
PIPA_DSL=$MU/Silicium-ACPI/Platforms/Xiaomi/pipa/Decompiled/DSDT.dsl

need() { [ -e "$1" ] || { echo "missing: $1 ($2)" >&2; exit 1; }; }
need "$MU/build_uefi.py"                      "clone Mu-Silicium first"
need "$MU/Binaries/alioth/QcomPkg/Drivers/UFSDxe" "Mu-Silicium submodules not checked out"
need "$PIPA_DSL"                              "Silicium-ACPI submodule not checked out"
need "$GEN"                                   "run this from a renegade-apollo checkout"
need "$DTB"                                   "edk2-msm checkout with apollo's FdtBlob_compat"
command -v iasl >/dev/null || { echo "iasl not installed (sudo apt install acpica-tools)" >&2; exit 1; }

echo "== package, config, device tree"
rm -rf "$MU/Platforms/Xiaomi/apolloPkg"
cp -r "$HERE/Platforms/Xiaomi/apolloPkg" "$MU/Platforms/Xiaomi/"
cp "$HERE/Resources/Configs/apollo.toml" "$MU/Resources/Configs/"
cp "$DTB" "$MU/Resources/DTBs/apollo.dtb"

echo "== ACPI"
OUT=$MU/Silicium-ACPI/Platforms/Xiaomi/apollo
TMP=$(mktemp -d)
python3 "$GEN" "$PIPA_DSL" "$TMP/Dsdt.asl" --drop PRTC --no-thermal | tail -2
mkdir -p "$OUT"
cp "$TMP/DSDT.aml" "$OUT/DSDT.aml"
cp "$HERE/Silicium-ACPI/Platforms/Xiaomi/apollo/AcpiTables.inf" "$OUT/"
rm -rf "$TMP"
ls -l "$OUT"

echo "done. Build with:  cd $MU && python3 build_uefi.py -d apollo"
