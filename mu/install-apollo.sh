#!/usr/bin/env bash
# Add apollo (Xiaomi Mi 10T / 10T Pro, SM8250) to a Mu-Silicium checkout, then build with
#   cd ~/Mu-Silicium && python3 build_uefi.py -d apollo        -> Mu-apollo.img
#
#   bash install-apollo.sh            (MU=~/Mu-Silicium, EDK=~/edk2-msm by default)
#
# What it installs:
#   Platforms/Xiaomi/apolloPkg        - derived from Silicium's aliothPkg (Poco F3, the closest SM8250 phone
#                                       with working Windows); SOC_TYPE 0 (SM8250), apollo SMBIOS; firmware binaries are Silicium's alioth set
#                                       (Xiaomi's shared Kona XBL, which also carries apollo's J3S panel config)
#   Resources/Configs/apollo.toml     - same boot image settings as pipa/alioth
#   Resources/DTBs/apollo.dtb         - apollo's stock device tree (board-id 0x2a), taken from edk2-msm
#   Silicium-ACPI/Platforms/Xiaomi/apollo/
#                                     - DSDT.aml generated by make-apollo-dsdt.py from pipa's table (no thermal
#                                       zones, no PRTC), plus AcpiTables.inf listing Silicium's Kona tables
#
# FB_SHIFT=0 (default) is the normal full-screen framebuffer. For debugging, FB_SHIFT=256 moves it 256 rows down
# so the text printed in the top-left corner (Windows bugcheck codes, UEFI exceptions) is not hidden by the
# punch-hole camera (multiples of 128 only; re-run the script to switch). With a shift, touch lines up only if
# apollotouch's TopRows parameter is set to the same value.
#
# LOGO=~/logo.img uses the Xiaomi logo from a dump of the phone's `logo` partition as the boot logo (UEFI and the
# Windows boot screen): make-boot-logo.py crops it into SiliciumPkg's BootLogo.bmp in this Mu-Silicium checkout
# only (the original is kept as BootLogo.bmp.silicium). LOGO_INDEX picks another image in the partition.
# LOGO=silicium puts Silicium's logo back. Without LOGO the logo is left as it is.
set -euo pipefail

HERE=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
MU=${MU:-$HOME/Mu-Silicium}
EDK=${EDK:-$HOME/edk2-msm}
FB_SHIFT=${FB_SHIFT:-0}
DROP=${DROP:-PRTC,PMAP}   # extra DSDT devices to leave out
NO_PEP=${NO_PEP:-1}       # 1: nothing waits on PEP0 and qcpep never binds (as in alioth); 0: pipa behaviour
LOGO=${LOGO:-}
LOGO_INDEX=${LOGO_INDEX:-0}
TOUCH=${TOUCH:-1}         # 1: add \_SB.TCH0 (APLO0001) for apollotouch.sys; 0: leave it out
GEN=$HERE/../uefi/apollo/make-apollo-dsdt.py
DTB=$EDK/Platform/Xiaomi/sm8250/FdtBlob_compat/apollo.dtb
PIPA_DSL=$MU/Silicium-ACPI/Platforms/Xiaomi/pipa/Decompiled/DSDT.dsl

need() { [ -e "$1" ] || { echo "missing: $1 ($2)" >&2; exit 1; }; }
need "$MU/build_uefi.py"                      "clone Mu-Silicium first"
need "$MU/Binaries/alioth/QcomPkg/Drivers/UFSDxe" "Mu-Silicium submodules not checked out"
need "$PIPA_DSL"                              "Silicium-ACPI submodule not checked out"
need "$GEN"                                   "run this from a renegade-apollo checkout"
need "$DTB"                                   "edk2-msm checkout with apollo's FdtBlob_compat"
command -v iasl >/dev/null || { echo "iasl not installed (sudo apt install acpica-tools)" >&2; exit 1; }

echo "== package, config, device tree"
rm -rf "$MU/Platforms/Xiaomi/apolloPkg"
cp -r "$HERE/Platforms/Xiaomi/apolloPkg" "$MU/Platforms/Xiaomi/"
cp "$HERE/Resources/Configs/apollo.toml" "$MU/Resources/Configs/"
cp "$DTB" "$MU/Resources/DTBs/apollo.dtb"

if [ "$FB_SHIFT" -ne 0 ]; then
    { [ $((FB_SHIFT % 128)) -eq 0 ] && [ "$FB_SHIFT" -lt 2400 ]; } \
        || { echo "FB_SHIFT must be a multiple of 128 below 2400" >&2; exit 1; }
    # Silicium takes the framebuffer from the "Display Reserved" region and PcdFrameBufferHeight.
    # Start it lower and shorten it by the same amount; its end address stays 0x9E400000.
    OFF=$((FB_SHIFT * 1080 * 4))
    FB_ADDR=$(printf '0x%08X' $((0x9C000000 + OFF)))
    FB_LEN=$(printf '0x%08X' $((0x02400000 - OFF)))
    MAP=$MU/Platforms/Xiaomi/apolloPkg/Library/MemoryMapLib/MemoryMapLib.c
    sed -i "s/{\"Display Reserved\",  0x9C000000, 0x02400000,/{\"Display Reserved\",  $FB_ADDR, $FB_LEN,/" "$MAP"
    sed -i "s/PcdFrameBufferHeight|2400\$/PcdFrameBufferHeight|$((2400 - FB_SHIFT))/" "$MU/Platforms/Xiaomi/apolloPkg/apollo.dsc"
    grep -q "$FB_ADDR, $FB_LEN" "$MAP" && grep -q "PcdFrameBufferHeight|$((2400 - FB_SHIFT))" "$MU/Platforms/Xiaomi/apolloPkg/apollo.dsc" \
        || { echo "could not apply FB_SHIFT" >&2; exit 1; }
    echo "== framebuffer shifted $FB_SHIFT rows: $FB_ADDR, height $((2400 - FB_SHIFT))"
fi

if [ -n "$LOGO" ]; then
    BL=$MU/Silicon/Silicium/SiliciumPkg/Include/Resources/BootLogo.bmp
    [ -e "$BL.silicium" ] || cp "$BL" "$BL.silicium"
    if [ "$LOGO" = silicium ]; then
        cp "$BL.silicium" "$BL"; echo "== boot logo: Silicium's"
    else
        need "$LOGO" "dump of the phone's logo partition"
        python3 "$HERE/make-boot-logo.py" "$LOGO" "$BL" --index "$LOGO_INDEX"
        echo "== boot logo: from $LOGO (image $LOGO_INDEX)"
    fi
fi

echo "== ACPI"
OUT=$MU/Silicium-ACPI/Platforms/Xiaomi/apollo
TMP=$(mktemp -d)
PEPARG=""; [ "$NO_PEP" = 1 ] && PEPARG=--no-pep
[ "$TOUCH" = 1 ] && PEPARG="$PEPARG --touch"
# shellcheck disable=SC2086
python3 "$GEN" "$PIPA_DSL" "$TMP/Dsdt.asl" --drop "$DROP" --no-thermal $PEPARG | tail -2
mkdir -p "$OUT"
cp "$TMP/DSDT.aml" "$OUT/DSDT.aml"
cp "$HERE/Silicium-ACPI/Platforms/Xiaomi/apollo/AcpiTables.inf" "$OUT/"
rm -rf "$TMP"
ls -l "$OUT"

echo "done. Build with:  cd $MU && python3 build_uefi.py -d apollo"
